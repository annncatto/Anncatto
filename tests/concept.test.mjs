import test from 'node:test';
import assert from 'node:assert/strict';
import {initialConcept,copyDesign,generateRobot,evaluateConcept,fk,inverseArm,sub,norm,sizeCandidates,exportMJCF,exportConceptURDF} from '../.build/concept-model.js';
import {PPO,gae} from '../.build/concept-rl.js';
import {loadPhysics,Physics} from '../.build/concept-physics.js';
const close=(a,b,t=1e-7)=>assert.ok(Math.abs(a-b)<t,`${a} != ${b}`);
test('canonical assemblies carry full inertias, correct DOF and connected member endpoints',()=>{
 for(const [robot,dof] of [['quadruped',12],['biped',23],['arm',7]]){
  const d=copyDesign(initialConcept);d.robot=robot;const m=generateRobot(d),poses=fk(m,m.home);assert.equal(m.active.length,dof);
  close(m.mass,m.nodes.reduce((s,n)=>s+n.mass,0));
  for(const n of m.nodes){assert.ok(n.mass>0);assert.ok(n.inertia.every(Number.isFinite));assert.ok(n.inertia.slice(0,3).every(x=>x>0));
   if(n.member){const children=m.nodes.filter(c=>c.parent===n.id);assert.ok(children.some(c=>norm(sub(c.offset,n.member.vector))<1e-8));}
   assert.ok(poses[n.id].p.every(Number.isFinite));}
  assert.match(exportConceptURDF(m),/ixx=/);assert.match(exportMJCF(m),/fullinertia=/);
 }
});
test('payload, selected material and sizing affect the intended design quantities',()=>{
 const d=copyDesign(initialConcept),m=generateRobot(d),part=m.nodes.find(n=>n.member).id;d.payload=2;close(generateRobot(d).mass-m.mass,2);
 d.parts[part]={properties:{E:140e9,rho:1550}};const a=evaluateConcept(generateRobot(d),m.home,part);assert.equal(a.material.E,140e9);
 const candidates=sizeCandidates(generateRobot(d),part).filter(c=>c.analysis);assert.ok(candidates.length);for(const c of candidates){assert.ok(c.analysis.utilization<=1.00001);assert.ok(c.analysis.deflectionUse<=1.00001);}
 d.parts[part].properties.E=NaN;assert.throws(()=>generateRobot(d));
});
test('spatial arm IK reaches a target generated by a different admissible pose',()=>{
 const d=copyDesign(initialConcept);d.robot='arm';const m=generateRobot(d),q={...m.home,j1:.3,j2:-.75,j3:1.2,j5:.45},target=fk(m,q).tool.p,r=inverseArm(m,m.home,target);assert.ok(r.error<.0005);assert.ok(norm(sub(fk(m,r.q).tool.p,target))<.0005);
});
test('GAE respects episode termination and PPO updates from actual samples',()=>{
 const samples=[{obs:[1,0],action:[.1],logp:0,value:0,reward:1,done:true}];close(gae(samples,999).returns[0],1);
 const p=new PPO(2,1,'design','stand');const batch=Array.from({length:128},(_,i)=>{const obs=[Math.sin(i),Math.cos(i)],a=p.act(obs);return{obs,...a,reward:a.action[0]*obs[0],done:i%32===31};});p.update(batch,0);assert.ok([...p.weights].some(x=>Math.abs(x)>1e-6));assert.ok([...p.weights].every(Number.isFinite));const saved=p.save(),loaded=new PPO(2,1,'design','stand');loaded.load(saved);assert.deepEqual(loaded.means([.1,.2]),p.means([.1,.2]));assert.throws(()=>new PPO(2,1,'other','stand').load(saved));
});
test('MuJoCo matches canonical FK and mass, and standing controllers remain upright',async()=>{
 const mj=await loadPhysics();
 for(const robot of ['quadruped','biped','arm']){
  const d=copyDesign(initialConcept);d.robot=robot;const m=generateRobot(d),p=new Physics(mj,m),poses=fk(m,m.home),snapshot=p.snapshot();
  close(p.model.body_mass.reduce((s,x)=>s+x,0),m.mass,1e-7);
  for(const n of m.nodes)for(let i=0;i<3;i++)close(snapshot.poses[n.id].p[i],poses[n.id].p[i],1e-8);
  for(let i=0;i<200;i++)p.step(m.active.map(()=>0));assert.equal(p.snapshot().fallen,false,robot);assert.ok(p.snapshot().tilt<.2,robot);p.dispose();
 }
});

test('disabled hinge and gripper joints preserve exported fixed poses',async()=>{
 const mj=await loadPhysics(),d=copyDesign(initialConcept);d.robot='arm';d.joints={j2:{active:false},gripper:{active:false}};const m=generateRobot(d),p=new Physics(mj,m),expected=fk(m,m.home),actual=p.snapshot();
 for(const n of m.nodes)for(let i=0;i<3;i++)close(actual.poses[n.id].p[i],expected[n.id].p[i],1e-8);
 assert.doesNotMatch(exportMJCF(m),/<equality>/);p.dispose();
});
